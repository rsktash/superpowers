/**
 * Superpowers plugin for OpenCode.ai
 *
 * Injects superpowers bootstrap context into the first user message.
 * Registers the bundled skills directory (no symlinks needed).
 *
 * The default export serves both plugin APIs: V2 calls `setup(ctx)`,
 * V1 (1.18.29+) calls `server()`.
 */

import path from 'path';
import fs from 'fs';
import os from 'os';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const superpowersSkillsDir = path.resolve(__dirname, '../../skills');
const BOOTSTRAP_MARKER = 'EXTREMELY_IMPORTANT';

// Simple frontmatter extraction (avoid dependency on skills-core for bootstrap)
const extractAndStripFrontmatter = (content) => {
  const match = content.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) return { frontmatter: {}, content };

  const frontmatterStr = match[1];
  const body = match[2];
  const frontmatter = {};

  for (const line of frontmatterStr.split('\n')) {
    const colonIdx = line.indexOf(':');
    if (colonIdx > 0) {
      const key = line.slice(0, colonIdx).trim();
      const value = line.slice(colonIdx + 1).trim().replace(/^["']|["']$/g, '');
      frontmatter[key] = value;
    }
  }

  return { frontmatter, content: body };
};

// Normalize a path: trim whitespace, expand ~, resolve to absolute
const normalizePath = (p, homeDir) => {
  if (!p || typeof p !== 'string') return null;
  let normalized = p.trim();
  if (!normalized) return null;
  if (normalized.startsWith('~/')) {
    normalized = path.join(homeDir, normalized.slice(2));
  } else if (normalized === '~') {
    normalized = homeDir;
  }
  return path.resolve(normalized);
};

const getBootstrapContent = () => {
  const skillPath = path.join(superpowersSkillsDir, 'using-superpowers', 'SKILL.md');
  if (!fs.existsSync(skillPath)) return null;

  const { content } = extractAndStripFrontmatter(fs.readFileSync(skillPath, 'utf8'));

  const toolMapping = `**Tool Mapping for OpenCode:**
When skills reference tools you don't have, substitute OpenCode equivalents:
- \`TodoWrite\` → \`todowrite\`
- \`Task\` tool with subagents → Use OpenCode's subagent system (@mention)
- \`Skill\` tool → OpenCode's native \`skill\` tool
- \`Read\`, \`Write\`, \`Edit\`, \`Bash\` → Your native tools

Use OpenCode's native \`skill\` tool to list and load skills.`;

  return `<${BOOTSTRAP_MARKER}>
You have superpowers.

**IMPORTANT: The using-superpowers skill content is included below. It is ALREADY LOADED - you are currently following it. Do NOT use the skill tool to load "using-superpowers" again - that would be redundant.**

${content}

${toolMapping}
</${BOOTSTRAP_MARKER}>`;
};

const loadSkills = () => {
  if (!fs.existsSync(superpowersSkillsDir)) return [];
  const skills = [];
  for (const entry of fs.readdirSync(superpowersSkillsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const skillPath = path.join(superpowersSkillsDir, entry.name, 'SKILL.md');
    if (!fs.existsSync(skillPath)) continue;
    const { frontmatter, content } = extractAndStripFrontmatter(fs.readFileSync(skillPath, 'utf8'));
    const id = frontmatter.name || entry.name;
    skills.push({ id, name: id, description: frontmatter.description, path: skillPath, content });
  }
  return skills;
};

// OpenCode rejects an agent file whose model is a Claude Code alias, and a config
// entry cannot rescue it, so OpenCode gets converted copies of agents/*.md.
const superpowersRoot = path.resolve(__dirname, '../..');
const superpowersAgentsDir = path.join(superpowersRoot, 'agents');
const GENERATED_MARKER = '# generated by the superpowers plugin from';
const MODEL_ALIASES = {
  opus: 'anthropic/claude-opus-5-5',
  sonnet: 'anthropic/claude-sonnet-5-5',
  haiku: 'anthropic/claude-haiku-5-5',
  fable: 'anthropic/claude-fable-5-1',
};
const LANE_CHILD_AGENTS = ['implementer', 'task-reviewer', 'miner'];

const opencodeConfigDir = () => {
  const home = os.homedir();
  const fromEnv = normalizePath(process.env.OPENCODE_CONFIG_DIR, home);
  if (fromEnv) return fromEnv;
  const xdg = normalizePath(process.env.XDG_CONFIG_HOME, home);
  return path.join(xdg || path.join(home, '.config'), 'opencode');
};

// Top-level keys only; indented lines belong to the key above (block scalars, lists, maps).
const parseAgentFrontmatter = (text) => {
  const match = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) return null;
  const raw = {};
  let key = null;
  for (const line of match[1].split('\n')) {
    const top = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (top) {
      key = top[1];
      raw[key] = { head: top[2].trim(), rest: [] };
    } else if (key) {
      raw[key].rest.push(line);
    }
  }
  const scalar = (k) => {
    const entry = raw[k];
    if (!entry) return undefined;
    if (entry.head === '|' || entry.head === '>') {
      const lines = entry.rest.filter((l) => l.trim());
      const indent = Math.min(...lines.map((l) => l.match(/^\s*/)[0].length));
      return lines.map((l) => l.slice(indent)).join(entry.head === '|' ? '\n' : ' ');
    }
    return entry.head.replace(/^["']|["']$/g, '');
  };
  const list = (k) => {
    const entry = raw[k];
    if (!entry) return undefined;
    if (entry.head) return entry.head.split(',').map((t) => t.trim()).filter(Boolean);
    return entry.rest.map((l) => l.replace(/^\s*-\s*/, '').trim()).filter(Boolean);
  };
  return {
    name: scalar('name'),
    description: scalar('description'),
    model: scalar('model'),
    tools: list('tools'),
    body: match[2],
  };
};

const toOpencodeModel = (model) => {
  if (!model || model === 'inherit') return undefined;
  if (model.includes('/')) return model;
  return MODEL_ALIASES[model] || `anthropic/${model}`;
};

const renderOpencodeAgent = (sourcePath, agent) => {
  const tools = agent.tools;
  const permissions = [{ action: 'subagent', resource: '*', effect: 'deny' }];
  if (tools?.includes('Agent')) {
    for (const child of LANE_CHILD_AGENTS) permissions.push({ action: 'subagent', resource: child, effect: 'allow' });
  }
  if (tools && !tools.includes('Edit') && !tools.includes('Write')) {
    permissions.push({ action: 'edit', resource: '*', effect: 'deny' });
  }
  if (tools && !tools.includes('Bash')) {
    permissions.push({ action: 'shell', resource: '*', effect: 'deny' });
  }

  const model = toOpencodeModel(agent.model);
  const lines = [
    '---',
    `${GENERATED_MARKER} ${sourcePath}; edits here are overwritten.`,
    `description: ${JSON.stringify(agent.description || agent.name)}`,
    'mode: subagent',
  ];
  if (model) lines.push(`model: ${JSON.stringify(model)}`);
  lines.push('permissions:');
  for (const p of permissions) {
    lines.push(`  - action: ${p.action}`, `    resource: ${JSON.stringify(p.resource)}`, `    effect: ${p.effect}`);
  }
  lines.push('---');

  let body = agent.body;
  if (tools?.includes('Agent')) {
    body += `

**Running in OpenCode:** a \`superpowers-beads:<name>\` agent is the \`<name>\` subagent, and the Agent tool is the \`subagent\` tool. Pass a model as a full ID (${Object.entries(MODEL_ALIASES).map(([a, id]) => `${a} → \`${id}\``).join(', ')}). SendMessage to a child means calling \`subagent\` again with that child's \`sessionID\`. Plugin files referenced under \`~/.claude/plugins/cache/rsktash/superpowers-beads/<version>/\` are in \`${superpowersRoot}/\`.
`;
  }
  return `${lines.join('\n')}\n${body}`;
};

const syncOpencodeAgents = () => {
  if (!fs.existsSync(superpowersAgentsDir)) return false;
  const targetDir = path.join(opencodeConfigDir(), 'agents');
  fs.mkdirSync(targetDir, { recursive: true });
  const isGenerated = (file) => fs.readFileSync(file, 'utf8').includes(GENERATED_MARKER);

  let changed = false;
  const written = new Set();
  for (const file of fs.readdirSync(superpowersAgentsDir)) {
    if (!file.endsWith('.md')) continue;
    const sourcePath = path.join(superpowersAgentsDir, file);
    const agent = parseAgentFrontmatter(fs.readFileSync(sourcePath, 'utf8'));
    if (!agent) continue;
    const target = path.join(targetDir, file);
    written.add(file);
    if (fs.existsSync(target) && !isGenerated(target)) continue;
    const content = renderOpencodeAgent(sourcePath, agent);
    if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === content) continue;
    const tmp = `${target}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, content);
    fs.renameSync(tmp, target);
    changed = true;
  }
  for (const file of fs.readdirSync(targetDir)) {
    const target = path.join(targetDir, file);
    if (!file.endsWith('.md') || written.has(file) || !isGenerated(target)) continue;
    fs.rmSync(target);
    changed = true;
  }
  return changed;
};

export default {
  id: 'superpowers',

  async setup(ctx) {
    if (syncOpencodeAgents()) await ctx.agent.reload();

    // Transform callbacks must be synchronous and replayable, so skills are read once up front.
    const skills = loadSkills();
    await ctx.skill.transform((editor) => {
      for (const skill of skills) {
        if (!editor.get(skill.id)) editor.add(skill);
      }
    });

    // Context-hook edits apply to the outgoing request only, so the bootstrap is
    // re-injected on every agent-loop call; keeping it in the first user message
    // (not the system prompt) keeps the prefix cacheable and avoids multiple
    // system messages, which break some models.
    await ctx.session.hook('context', (event) => {
      const bootstrap = getBootstrapContent();
      if (!bootstrap) return;
      const idx = event.messages.findIndex((m) => m.role === 'user');
      if (idx === -1) return;
      const first = event.messages[idx];
      if (first.content.some((p) => p.type === 'text' && p.text.includes(BOOTSTRAP_MARKER))) return;
      const content = [{ type: 'text', text: bootstrap }, ...first.content];
      event.messages[idx] = new first.constructor({ ...first, content });
    });
  },

  async server() {
    return {
      config: async (config) => {
        config.skills = config.skills || {};
        config.skills.paths = config.skills.paths || [];
        if (!config.skills.paths.includes(superpowersSkillsDir)) {
          config.skills.paths.push(superpowersSkillsDir);
        }
      },

      'experimental.chat.messages.transform': async (_input, output) => {
        const bootstrap = getBootstrapContent();
        if (!bootstrap || !output.messages.length) return;
        const firstUser = output.messages.find((m) => m.info.role === 'user');
        if (!firstUser || !firstUser.parts.length) return;
        if (firstUser.parts.some((p) => p.type === 'text' && p.text.includes(BOOTSTRAP_MARKER))) return;
        const ref = firstUser.parts[0];
        firstUser.parts.unshift({ ...ref, type: 'text', text: bootstrap });
      },
    };
  },
};
